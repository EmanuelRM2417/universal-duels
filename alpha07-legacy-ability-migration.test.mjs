import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('./public/editor/index.html',import.meta.url),'utf8');
assert(!source.includes('Configurar Carga')&&!source.includes('Configurar Sobrevivir'),'Legacy separate controls must be removed');
assert(source.includes('effect_immunity'),'New effect must be available in standard rule selector');
assert(source.includes('streakEffectMode'),'Streak must offer normal/per-turn mode');
const start=source.indexOf('    function migrateLegacyAbility(definition){'),end=source.indexOf('    function renderBuilder(definition)',start);
assert(start>0&&end>start);
const sandbox={structuredClone,catalogCategory:{value:'abilities'}};
vm.runInNewContext(source.slice(start,end)+'\nthis.convert=migrateLegacyAbility;',sandbox);
const legacy={consecutiveAttack:{conditionMode:'hit',minStreak:2,maxStreak:5,damagePerStack:10,speedStages:2},survive:{chance:80,hpPercent:50,limit:2,limitScope:'entry',sources:['move']},rules:[{event:'on_enter',condition:{type:'always'},target:'self',action:{type:'heal',value:20}}]};
const updated=sandbox.convert(legacy);
assert.equal(legacy.rules.length,1,'Legacy source must remain untouched');
assert.equal(updated.rules.length,4,'Preserve existing rule and convert charge/survive');
assert.equal(updated.consecutiveAttack,undefined);assert.equal(updated.survive,undefined);
assert.equal(updated.rules.find(x=>x.action.type==='survive').action.value,1);
assert.equal(updated.rules.find(x=>x.action.type==='survive').action.limitScope,'entry');
assert.equal(updated.rules.find(x=>x.action.type==='survive').chance,80);
assert.equal(updated.rules.find(x=>x.action.type==='final_damage').condition.value,'hit:2:5');
assert.equal(updated.rules.find(x=>x.action.type==='stat_change').streakEffectMode,'per_turn');
assert.equal(sandbox.convert(updated).rules.length,4,'Re-opening an already-migrated ability must not duplicate effects');
console.log('Editor: migration of legacy Carga/Sobrevivir to standard rules, no duplication, compatibility passed');
