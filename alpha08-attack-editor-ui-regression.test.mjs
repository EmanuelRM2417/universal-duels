import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateRules} from './catalog-validation.js';
const html=readFileSync(new URL('./public/editor/index.html',import.meta.url),'utf8');
const main=readFileSync(new URL('../universal-duels-main/public/index.html',import.meta.url),'utf8');
const training=readFileSync(new URL('../universal-duels-main/public/practice.html',import.meta.url),'utf8');
assert.match(html,/labeledControl\(attackGrid,'Mensaje de este Atacar/, 'La forma crea un input de narrador de impacto');
assert.match(html,/narratorMessage:valA\('attackNarrator'\)\.trim\(\)/,'El formulario serializa el mensaje exacto del Atacar');
assert.match(html,/streakEditorHelp/,'La racha incluye ayuda contextual');
assert.match(html,/advancedCheck\.checked=!!\(rule\.action\?\.perRound\|\|\(rule\.condition\?\.type!==\x27streak_count\x27/,'Racha normal no muestra parámetros avanzados solo por perStack');
assert.match(html,/conditionValue\.closest\('label'\)\.hidden=\['','streak_count'/,'Evita mostrar el valor interno hit:1:');
assert.match(html,/Mensaje de este Atacar/);
assert.match(html,/La potencia de \[MOVIMIENTO\]/);
assert.match(html,/udNarratorExtraPattern/,'Se pueden añadir patrones faltantes sin modificar originales');
assert.match(main,/udTutorialPanelReference/);
assert.match(main,/bottom:auto!important/,'i vuelve a esquina superior');
assert.match(main,/title="\$\{cd\} turnos de espera">\$\{cd\}<\/span>/,'Cooldown es solamente un número');
assert.match(training,/title="\$\{cd\} turnos de espera">\$\{cd\}<\/span>/);
const makeRule=(event,action)=>({event,condition:{type:'always',value:''},conditions:[],target:'target',action,chance:100,duration:0,limit:0});
const base={type:'fuego',category:'special',power:80,accuracy:100,criticalChance:10,target:'target',chance:100,animate:true,narratorMessage:'Bomba volcánica explotó contra [OBJETIVO].',rules:[makeRule('on_hit',{type:'apply_status',value:'stun'})]};
validateRules({rules:[makeRule('on_attack',{type:'attack',attack:base})]},'moves');
assert.throws(()=>validateRules({rules:[makeRule('on_attack',{type:'attack',attack:{...base,narratorMessage:'x'.repeat(241)}})]},'moves'));
assert.throws(()=>validateRules({rules:[makeRule('on_attack',{type:'attack',attack:{...base,rules:[makeRule('on_hit',{type:'attack',attack:base})]}})]},'moves'));
console.log('Editor: mensaje único, racha intuitiva, validación y panel/guía: OK');
