import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=name=>readFileSync(new URL(name,import.meta.url),'utf8');
const cat=read('./public/catalog.html'),tut=read('./public/tutorial.html'),practice=read('./public/practice.html'),main=read('./public/index.html'),format=read('./public/narrator-templates.js');
assert.match(cat,/role="tab"[^>]*>Personajes<\/button>/,'Catálogo: pestaña Personajes');
assert.match(cat,/role="tab"[^>]*>Objetos<\/button>/,'Catálogo: pestaña Objetos');
assert.match(cat,/data\.catalog\[cat\]/,'Catálogo: búsqueda por colección');
assert.match(cat,/api\/item-sprites/,'Catálogo: imagen de consumible');
assert.match(cat,/ud-catalog-tab-viewed/,'Catálogo: seguimiento de las dos pestañas en tutorial');
assert.match(tut,/<section id="catalogo">/,'Guía pública explica el catálogo');
assert.match(tut,/id="objetos"/,'Guía pública explica consumibles');
assert.match(main,/\['catalogo','Catálogo'\]/,'Tutorial integrado permite editar la sección del catálogo');
for(const step of ['catalog','attack','info','switch','effects','consumable','rounds'])assert.ok(practice.includes(step+':')||practice.includes("'"+step+"'"),'Tutorial debe imponer la etapa '+step);
assert.match(practice,/if\(!ok\)\{udUpdateCoach\(\);notice\(/,'Tutorial impide acción que no corresponde');
assert.match(practice,/udGuideProgress\.catalogCharacters=true/,'Debe mirar Personajes');
assert.match(practice,/udGuideProgress\.catalogItems=true/,'Debe mirar Objetos');
const sandbox={window:{}};vm.runInNewContext(format,sandbox);
const fmt=sandbox.window.udNarratorFormat;
assert.equal(fmt('Luna consumió Manzana.',[{pattern:'[PERSONAJE] consumió [CONSUMIBLE].',replacement:'[PERSONAJE] utilizó [CONSUMIBLE].'}]),'Luna utilizó Manzana.','Mensaje de consumo se puede editar desde Editor');
assert.equal(fmt('Sombra recibe 12 de daño.',[{pattern:'[PERSONAJE] recibe [DAÑO] de daño.',replacement:'[PERSONAJE] sufre [DAÑO] puntos de daño.'}]),'Sombra sufre 12 puntos de daño.','Mensaje de daño funciona');
assert.equal(fmt('Sin reglas',[]),'Sin reglas','Sin personalización conserva mensaje original');
console.log('Catálogo de dos pestañas, tutorial obligatorio y narrador personalizable: OK');
