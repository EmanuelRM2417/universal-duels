import assert from 'node:assert/strict';
import {simulate} from './battle-engine.js';
import {basicStageFactor, hitChance} from './stat-math.js';

const rule=(event,type,target='self',value='100',extra={})=>({event,condition:{type:'always'},target,action:{type,value},chance:100,duration:0,limit:0,...extra});
const entity=(id,types=['fuego'])=>({id,name:id,definition:{types,hp:500,attack:100,defense:100,specialAttack:100,specialDefense:100,speed:100,moveIds:['triple','idle','single'],uniqueMoveId:'single',globalAbilityId:'blank',uniqueAbilityId:'blank'}});
const mv=(id,{rules=[],multihit,accuracy=0,power=40}={})=>({id,name:id,definition:{type:'fuego',category:power?'physical':'status',power,accuracy,criticalChance:0,priority:0,rules,...(multihit?{multihit}:{})}});
const basic={entities:{a:entity('a'),b:entity('b')},moves:{triple:mv('triple',{multihit:{min:3,max:3},rules:[rule('on_attack','damage','self','30'),rule('on_hit','heal_from_damage','self','100')]}),idle:mv('idle',{power:0}),single:mv('single')},abilities:{blank:{id:'blank',definition:{rules:[]}}},statuses:{},effects:{},fields:{},scenarios:{},weathers:{}};
const run=(catalog,opts={})=>simulate({catalog,left:'a',right:'b',turns:1,leftMove:'triple',rightMove:'idle',randomSource:()=>.999,...opts});
const each=run(structuredClone(basic));
const eachHealing=each.log.filter(x=>/recupera .*daño infligido/.test(x));
assert.equal(eachHealing.length,3,'heal_from_damage must run on EACH hit, not only the last');
const once=structuredClone(basic);
once.moves.triple.definition.rules[1].chainTiming='chain';
const chain=run(once);
const chainHealing=chain.log.filter(x=>/recupera .*daño infligido/.test(x));
assert.equal(chainHealing.length,1,'an individual chainTiming=chain effect must execute once');
assert.equal(chain.left.hp,each.left.hp,'chain healing should use ALL actual chain damage (not just final hit)');
const mixed=structuredClone(basic);
mixed.moves.triple.definition.rules.push(rule('on_hit','stat_change','self','1',{chainTiming:'chain',action:{type:'stat_change',stat:'speed',value:1}}));
const m=run(mixed);assert.equal(m.left.stages.speed,1,'a per-chain stage rule can coexist with per-hit healing');
assert.equal(m.log.filter(x=>/recupera .*daño infligido/.test(x)).length,3);
const legacy=structuredClone(basic);legacy.moves.triple.definition.multihit.effects='chain';
const l=run(legacy);assert.equal(l.log.filter(x=>/recupera .*daño infligido/.test(x)).length,1,'legacy global chain settings remain compatible');
const forced=structuredClone(basic);
forced.moves.triple.definition.rules=[rule('on_attack','force_miss'),rule('on_miss','stat_change','self','2',{action:{type:'stat_change',stat:'attack',value:2}})];
const fm=run(forced);assert.ok(fm.log.some(x=>x.includes('falló contra')),'force_miss must override infallible accuracy=0');
assert.equal(fm.right.hp,500,'forced miss cannot inflict damage');
assert.equal(fm.left.stages.attack,2,'on_miss rules trigger after force_miss');
assert.ok(fm.log.findIndex(x=>x.includes('usó triple'))<fm.log.findIndex(x=>x.includes('falló contra')),'narration must announce move before miss');
const frozen=structuredClone(basic);
frozen.statuses.freeze={id:'freeze',name:'Congelación',definition:{rules:[rule('on_attack','do_nothing')]}};
frozen.abilities.preFrozen={id:'preFrozen',definition:{rules:[rule('on_enter','apply_status','self','freeze')]}};frozen.entities.a.definition.globalAbilityId='preFrozen';frozen.moves.triple.definition.rules=[];
const fr=run(frozen);assert.equal(fr.right.hp,500,'do_nothing cancels movement while the status is active');
assert.ok(fr.log.some(x=>x.includes('no puede actuar')));
assert.ok(fr.log.findIndex(x=>x.includes('usó triple'))<fr.log.findIndex(x=>x.includes('no puede actuar')));
// Todos los efectos basados en daño reciben cada impacto, tanto del atacante
// como del objetivo que está recibiendo el daño.
const recoil=structuredClone(basic);
recoil.moves.triple.definition.rules=[rule('on_hit','damage_from_damage','self','10')];
const rec=run(recoil);
assert.equal(rec.log.filter(x=>x.includes('de daño por el daño infligido')).length,3,'recoil from damage on each hit');
const healedReceived=structuredClone(basic);
healedReceived.moves.triple.definition.rules=[];
healedReceived.abilities.absorb={id:'absorb',definition:{rules:[rule('on_damage_taken','heal_from_received_damage','self','50')]}};
healedReceived.entities.b.definition.globalAbilityId='absorb';
const hr=run(healedReceived);
assert.equal(hr.log.filter(x=>x.includes('recupera')&&x.includes('daño recibido')).length,3,'healing from damage taken per hit');
const punished=structuredClone(healedReceived);
punished.abilities.absorb.definition.rules=[rule('on_damage_taken','damage_from_received_damage','self','10')];
const dr=run(punished);
assert.equal(dr.log.filter(x=>x.includes('adicionales por daño recibido')).length,3,'self-damage from received damage per hit');
const neutral=structuredClone(basic);neutral.moves.triple=mv('triple',{power:40});
const nr=run(neutral);const damage=500-nr.right.hp;
const weak=structuredClone(neutral);weak.entities.b.definition.types=['agua','rayo'];
const w=run(weak,{chart:{fuego:{agua:'eficaz',rayo:'eficaz'}}});
assert.ok(500-w.right.hp>damage,'+30% per weakness increases damage');
const resistant=structuredClone(neutral);resistant.entities.b.definition.types=['agua','rayo'];
const rr=run(resistant,{chart:{fuego:{agua:'ineficaz',rayo:'ineficaz'}}});
assert.ok(500-rr.right.hp<damage,'-20% per resistance reduces damage');
assert.equal(basicStageFactor(1),1.15);assert.equal(basicStageFactor(4),1.60);assert.equal(basicStageFactor(-4),.8);
assert.equal(hitChance(80,{stages:{accuracy:2}},{stages:{evasion:4}}),72);
assert.equal(hitChance(20,{stages:{accuracy:-10}},{stages:{evasion:10}}),10);
assert.equal(hitChance(0,{stages:{accuracy:-10}},{stages:{evasion:10}}),100);
console.log('PASS: multihit per-rule timing, full chain damage healing, legacy, on_miss, infallible forced miss, freeze, narration, type ratios, new stages');
