import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {releaseResources} from './release-assets.js';
const editor=readFileSync(new URL('./public/editor/index.html',import.meta.url),'utf8');
const main=readFileSync(new URL('../universal-duels-main/public/index.html',import.meta.url),'utf8');
const practice=readFileSync(new URL('../universal-duels-main/public/practice.html',import.meta.url),'utf8');
const mainWorker=readFileSync(new URL('../universal-duels-main/worker.js',import.meta.url),'utf8');
assert.match(editor,/id="udNarratorSearch"/);
assert.match(editor,/const current=changes\.get\(pattern\)\|\|pattern/,'search and display use the customized text');
assert.match(editor,/preview\.textContent=changes\.get\(pattern\)\|\|pattern/);
assert.match(editor,/input\.dataset\.narratorPattern=pattern/,'original kept as immutable internal key');
assert.doesNotMatch(editor,/original\.placeholder='Mensaje original/,'original text input eliminated');
assert.doesNotMatch(editor,/id="udNarratorAdd"/,'no unkeyed free-pattern editor');
assert.match(editor,/for\(const r of layout\.narratorRules\|\|\[\]\)/,'existing narrator rules loaded');
assert.match(editor,/\[\.\.\.changes\.keys\(\)\]\.filter/,'legacy patterns not in the template catalog preserved');
assert.match(editor,/id="udNeutralSceneFile"/);
assert.match(editor,/id="udNeutralScenePreview"/);
assert.match(editor,/window\.udNeutralDraftAvailable/);
assert.match(editor,/!data\?\.scenario&&window\.udNeutralDraftAvailable/,'Lab only restores neutral for absent scenario');
assert.match(main,/backgroundId=data\.scenario\?sc\.imageId:udNeutralSceneId/,'Main respects active scenario, then neutral');
assert.match(practice,/!data\?\.scenario\?udNeutralSceneId:''/,'Practice restores neutral after scenario expires');
assert.match(mainWorker,/id==='ud-neutral-default'&&snap\.assets\?\.environment/,'public route requires published neutral asset');
const draft=new Map();const published=new Map();
const png={body:new Uint8Array([137,80,78,71,13,10,26,10,5]),etag:'neutral-png',httpMetadata:{contentType:'image/png'}};
const r2={async head(key){const x=draft.get(key)||published.get(key);return x?{etag:x.etag}:null;},async get(key){return draft.get(key)||published.get(key)||null;},async put(key,body,metadata){published.set(key,{body,etag:'neutral-png',httpMetadata:metadata.httpMetadata});}};
const catalog={entities:{},scenarios:{},weathers:{},tutorial:{}};
const before=await releaseResources({EDITOR_SPRITES:r2},catalog,'rev0',{},[],{});
assert.equal(before.assets.environment['scenarios/ud-neutral-default'],undefined,'without uploaded PNG, grey fallback is preserved');
draft.set('environment/scenarios/ud-neutral-default.png',png);
const after=await releaseResources({EDITOR_SPRITES:r2},catalog,'rev1',{},[],{});
assert.equal(after.assets.environment['scenarios/ud-neutral-default'],'published/rev1/environment/scenarios/ud-neutral-default.png');
assert.equal(published.size,1,'published only on manual release');
const reused=await releaseResources({EDITOR_SPRITES:r2},catalog,'rev2',{assets:after.assets},[],{});
assert.equal(reused.assets.environment['scenarios/ud-neutral-default'],after.assets.environment['scenarios/ud-neutral-default']);
assert.equal(published.size,1,'unchanged neutral PNG is not duplicated');
draft.clear();const preserved=await releaseResources({EDITOR_SPRITES:r2},catalog,'rev3',{assets:after.assets},[],{});
assert.equal(preserved.assets.environment['scenarios/ud-neutral-default'],after.assets.environment['scenarios/ud-neutral-default'],'existing public backdrop survives missing draft');
console.log('Alpha 0.8: narrator read-only originals + search by replacement, neutral private upload/release, grey fallback and reuse OK');
